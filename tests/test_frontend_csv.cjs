/* Browser CSV parser, request contract and no-preload smoke checks. No npm dependencies. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const root = path.join(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'frontend/app.js'),'utf8');
const start = source.indexOf('function parseCsv(text) {');
const end = source.indexOf('\nfunction loadRows(items, source) {',start);
assert(start >= 0 && end > start, 'parser can be extracted');
const parseCsv = vm.runInNewContext(`(${source.slice(start,end)})`, {DISPLAY_LIMIT:20});
const sample = fs.readFileSync(path.join(root,'frontend/sample_feedback.csv'),'utf8');
const result = parseCsv(sample);
assert.equal(result.length,16);
assert.equal(result[0].feedback_id,'FB001');
assert.equal(result[0].market,'Italy');
assert.equal(parseCsv('feedback_id,comment,market\nX01,"Hello, world",UK\n')[0].comment,'Hello, world');
assert.equal(parseCsv('feedback_id,comment\nX01,"Line 1\nLine 2"\n')[0].comment,'Line 1\nLine 2');
assert.throws(()=>parseCsv('feedback_id,comment\nX01,test\nX01,test2\n'),/duplicate/);
assert.throws(()=>parseCsv('id,text\nX,hi\n'),/feedback_id/);
assert.throws(()=>parseCsv('feedback_id,comment\nX01,\n'),/Invalid or duplicate/);
assert.match(fs.readFileSync(path.join(root,'frontend/feedback_template.csv'),'utf8'), /^feedback_id,date,channel,market,product_category,comment\n$/);
console.log('CSV parser and template: 8 assertions passed');

const html = fs.readFileSync(path.join(root,'frontend/index.html'),'utf8');
const css = fs.readFileSync(path.join(root,'frontend/styles.css'),'utf8');
assert.match(html, /No feedback loaded · CSV required/);
assert.match(html, /id="analyzeBtn"[^>]*disabled/);
assert.match(html, /feedback_template\.csv/);
assert.doesNotMatch(html, /Try demo data|sampleBtn/);
assert.match(html, /id="marketInsights"/);
assert.match(html, /id="executiveSummary"/);
assert(html.indexOf('href="#insights"') < html.indexOf('href="#markets"'));
assert(html.indexOf('href="#markets"') < html.indexOf('href="#categories"'));
assert(html.indexOf('href="#categories"') < html.indexOf('href="#channels"'));
assert(html.indexOf('href="#channels"') < html.indexOf('href="#feedback"'));
assert(html.indexOf('id="markets"') < html.indexOf('id="categories"'));
assert(html.indexOf('id="categories"') < html.indexOf('id="channels"'));
assert(html.indexOf('id="channels"') < html.indexOf('id="feedback"'));
assert(html.indexOf('id="briefing"') < html.indexOf('id="actions"'));
assert.match(source, /market:market \|\| ""/);
assert.match(source, /product_category:product_category \|\| ""/);
assert.match(source, /channel:channel \|\| ""/);
assert.match(source, /renderCategories\(\)/);
assert.match(source, /renderChannels\(\)/);
assert.match(html, /id="categoryInsights"/);
assert.match(html, /id="channelInsights"/);
assert.doesNotMatch(source, /await loadSample\(\)/);
assert.match(source, /Limitations and unknowns/);
assert.doesNotMatch(source, /Not yet established:/);
assert.match(css, /position:\s*sticky/);
console.log('Dashboard integration: navigation, request fields, and segment UI checks passed');
